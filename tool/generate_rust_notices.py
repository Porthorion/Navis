#!/usr/bin/env python3
"""Generate Windows SMTC registry-crate notices from Cargo's locked graph."""

import hashlib
import json
from pathlib import Path
import subprocess


def main():
    root = Path(__file__).resolve().parent.parent
    metadata = json.loads(subprocess.check_output(
        [
            'cargo', 'metadata', '--format-version', '1',
            '--filter-platform', 'x86_64-pc-windows-msvc', '--locked', '--offline',
        ],
        cwd=root / 'third_party/navis_windows_smtc/rust',
        text=True,
    ))
    resolved = {node['id'] for node in metadata['resolve']['nodes']}
    crates = sorted(
        (package for package in metadata['packages']
         if package['id'] in resolved
         and (package['source'] or '').startswith('registry+')),
        key=lambda package: (package['name'], package['version']),
    )
    if not crates:
        raise RuntimeError('No resolved registry crates found')

    output = [
        'Windows media controls — Rust crate licences',
        'Generated by python3 tool/generate_rust_notices.py.',
        'Source: the locked x86_64-pc-windows-msvc Cargo dependency graph.',
        'Each distinct licence text appears once after the crate inventory.',
        '',
    ]
    texts = {}
    for crate in crates:
        identity = f"{crate['name']} {crate['version']}"
        directory = Path(crate['manifest_path']).parent
        files = set()
        for pattern in ('LICENSE*', 'COPYING*', 'UNLICENSE'):
            files.update(file for file in directory.glob(pattern) if file.is_file())
        if crate['license_file']:
            declared = directory / crate['license_file']
            if not declared.is_file():
                raise FileNotFoundError(f'{identity}: declared licence file missing')
            files.add(declared)
        expression = crate['license']
        if not expression:
            # allo-isolate omits the manifest field but ships Apache-2.0 text.
            expression = (
                'Apache-2.0 (from LICENSE; manifest licence unspecified)'
                if crate['name'] == 'allo-isolate'
                and any('Apache License' in file.read_text(encoding='utf-8')
                        and 'Version 2.0' in file.read_text(encoding='utf-8')
                        for file in files)
                else 'licence expression unspecified in manifest'
            )
        output.append(f'{identity} — {expression}')
        if not files:
            output.append('No licence file found in the crate manifest directory.')
        for file in sorted(files):
            text = file.read_text(encoding='utf-8').strip()
            if not text:
                raise ValueError(f'{identity}: empty licence file {file.name}')
            digest = hashlib.sha256(text.encode('utf-8')).hexdigest()
            if digest not in texts:
                texts[digest] = (text, [])
            texts[digest][1].append(f'{identity} ({file.name})')
            output.append(f'  {file.name}: licence text {digest}')
        output.append('')

    output.extend(['Distinct licence texts', '======================', ''])
    for digest, (text, users) in texts.items():
        output.extend([
            f'Licence text {digest}',
            'Used by:',
            *(f'  {user}' for user in users),
            '',
            text,
            '',
        ])
    destination = root / 'assets/licenses/windows-smtc-crates.txt'
    destination.write_text('\n'.join(output), encoding='utf-8')
    print(f'Generated notices for {len(crates)} crates, {len(texts)} distinct texts.')


if __name__ == '__main__':
    main()
