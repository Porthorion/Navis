#!/usr/bin/env dart

import 'dart:io';

/// Regenerates the MIT colour table from the checked-in, filtered CSV.
void main() {
  final root = Platform.script.resolve('../');
  final source = File.fromUri(
    root.resolve('tool/data/color_names/colornames.bestof.csv'),
  );
  // The filtered dataset has two columns and no embedded newlines. Quoted
  // names may contain commas or doubled quotes, per CSV escaping rules.
  final rowPattern = RegExp(r'^("(?:[^"]|"")*"|[^,]*),(#[0-9a-fA-F]{6})$');
  final lines = source.readAsLinesSync();
  if (lines.first != 'name,hex') {
    throw const FormatException('Expected name,hex CSV header');
  }
  final rows = <(String, int)>[];
  for (final line in lines.skip(1)) {
    final match = rowPattern.firstMatch(line);
    if (match == null) throw FormatException('Invalid colour row: $line');
    var name = match[1]!;
    if (name.startsWith('"')) {
      name = name.substring(1, name.length - 1).replaceAll('""', '"');
    }
    rows.add((name, int.parse(match[2]!.substring(1), radix: 16)));
  }
  rows.sort((a, b) => a.$1.compareTo(b.$1));
  final seen = <int>{};
  final output = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND.')
    ..writeln('// Generated by dart run tool/generate_color_names.dart.')
    ..writeln('// Source: meodai/color-names v14.51.0, src/colornames.csv;')
    ..writeln('// rows marked "x" in "good name". MIT © David Aerne.')
    ..writeln('// See tool/data/color_names/README.md and LICENSE.')
    ..writeln()
    ..writeln('const List<(String, int)> kColorNameTable = <(String, int)>[');
  for (final (name, hex) in rows) {
    if (!seen.add(hex)) continue;
    final escaped = name
        .replaceAll(r'\', r'\\')
        .replaceAll("'", r"\'")
        .replaceAll(r'$', r'\$');
    output.writeln(
      "  ('$escaped', 0x${hex.toRadixString(16).padLeft(6, '0').toUpperCase()}),",
    );
  }
  output.writeln('];');
  final destination = File.fromUri(
    root.resolve('lib/src/features/settings/domain/color_name_table.g.dart'),
  );
  destination.writeAsStringSync(output.toString());
  // Keep regeneration identical to the repository's normal formatting gate.
  final result = Process.runSync(Platform.resolvedExecutable, <String>[
    'format',
    destination.path,
  ]);
  if (result.exitCode != 0) {
    stderr.write(result.stderr);
    exit(result.exitCode);
  }
  stdout.writeln('Generated ${seen.length} unique colour names.');
}
